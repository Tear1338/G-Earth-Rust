import java.util.regex.Pattern;

// Generates Latin-1 property bitmaps from the Java runtime used by beta-29's oracle.
public class JavaRegexPropertyGenerator {
    public static void main(String[] args) throws Exception {
        if (args.length > 0 && args[0].equals("--names")) {
            for (String row : java.nio.file.Files.readAllLines(java.nio.file.Path.of("tests/java_unicode_names.txt"))) {
                String kind = row.substring(0, 1);
                String name = row.substring(2, row.lastIndexOf('='));
                for (int f = 0; f < 8; f++) {
                    int flags = ((f & 1) != 0 ? Pattern.CASE_INSENSITIVE : 0)
                        | ((f & 2) != 0 ? Pattern.UNICODE_CASE : 0)
                        | ((f & 4) != 0 ? Pattern.UNICODE_CHARACTER_CLASS : 0);
                    Pattern p = Pattern.compile("\\p{" + (kind.equals("S") ? "sc=" : "blk=") + name + "}", flags);
                    byte[] bits = new byte[32];
                    for (int b = 0; b < 256; b++) if (p.matcher(String.valueOf((char)b)).matches()) bits[b / 8] |= 1 << (b % 8);
                    System.out.println(kind + ":" + name + ":" + f + "=" + java.util.HexFormat.of().formatHex(bits));
                }
            }
            return;
        }
        boolean oracle = args.length > 0 && args[0].equals("--oracle");
        String[] names = ("L Lu Ll Lt Lm Lo M Mn Mc Me N Nd Nl No Z Zs Zl Zp C Cc Cf Co Cs Cn " +
            "P Pc Pd Ps Pe Pi Pf Po S Sm Sc Sk So LC L1 ASCII Lower Upper Alpha Digit Alnum Punct Graph Print Blank Cntrl XDigit Space " +
            "javaLowerCase javaUpperCase javaTitleCase javaDigit javaDefined javaLetter javaLetterOrDigit javaJavaIdentifierStart javaJavaIdentifierPart javaUnicodeIdentifierStart javaUnicodeIdentifierPart javaIdentifierIgnorable javaSpaceChar javaWhitespace javaISOControl javaMirrored javaAlphabetic javaIdeographic " +
            "IsAlphabetic IsIdeographic IsLetter IsLowercase IsUppercase IsTitlecase IsPunctuation IsControl IsWhite_Space IsDigit IsHex_Digit IsAssigned IsNoncharacter_Code_Point IsJoin_Control IsLower IsUpper IsAlpha IsAlnum IsPunct IsGraph IsPrint IsBlank IsCntrl IsXDigit IsSpace IsWord IsASCII IsLu IsL IsLatin IsCommon IsInherited InBasic_Latin InLatin_1_Supplement").split(" ");
        if (!oracle) System.out.println("// Generated by tests/JavaRegexPropertyGenerator.java using Java 21.\n// Index bits: case-insensitive, Unicode case, Unicode character classes.\npub(super) const JAVA_REGEX_PROPERTIES: &[(&str, [[u8; 32]; 8])] = &[");
        for (String name : names) {
            Pattern[] compiled = new Pattern[8];
            try {
                for (int f = 0; f < 8; f++) {
                    int flags = ((f & 1) != 0 ? Pattern.CASE_INSENSITIVE : 0)
                        | ((f & 2) != 0 ? Pattern.UNICODE_CASE : 0)
                        | ((f & 4) != 0 ? Pattern.UNICODE_CHARACTER_CLASS : 0);
                    compiled[f] = Pattern.compile("\\p{" + name + "}", flags);
                }
            } catch (IllegalArgumentException ignored) { continue; }
            if (!oracle) System.out.println("    (\"" + name + "\", [");
            for (int flag = 0; flag < compiled.length; flag++) {
                Pattern pattern = compiled[flag];
                byte[] bits = new byte[32];
                for (int b = 0; b < 256; b++) if (pattern.matcher(String.valueOf((char)b)).matches()) bits[b / 8] |= 1 << (b % 8);
                if (oracle) {
                    System.out.println(name + ":" + flag + "=" + java.util.HexFormat.of().formatHex(bits));
                } else {
                    System.out.print("        [");
                    for (int i = 0; i < bits.length; i++) System.out.printf("%s0x%02x", i == 0 ? "" : ", ", bits[i] & 255);
                    System.out.println("],");
                }
            }
            if (!oracle) System.out.println("    ]),");
        }
        if (!oracle) System.out.println("];");
    }
}
